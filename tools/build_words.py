#!/usr/bin/env python3
"""Builds js/words.js from tools/answers.txt, tools/extra_valid.txt and the
public-domain Webster's 2nd dictionary that ships with macOS (/usr/share/dict/web2).

WARNING: the answer order decides which word is used on which day.
Re-running this script reshuffles the answers and so changes past and
future daily puzzles. Only re-run it before launch or when you accept that.
"""
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT = Path("/usr/share/dict/web2")
SEED = 20261115

FIVE = re.compile(r"^[a-z]{5}$")


def read_words(path):
    return [w.strip().lower() for w in path.read_text().split() if w.strip()]


def main():
    answers_raw = read_words(ROOT / "tools" / "answers.txt")
    bad = [w for w in answers_raw if not FIVE.match(w)]
    if bad:
        raise SystemExit(f"answers.txt has non 5-letter entries: {bad}")
    seen, answers = set(), []
    for w in answers_raw:
        if w not in seen:
            seen.add(w)
            answers.append(w)
    dupes = len(answers_raw) - len(answers)

    # Lowercase-only entries skip proper nouns.
    dict_words = [w for w in DICT.read_text().split() if re.match(r"^[a-z]+$", w)]
    by_len = {}
    for w in dict_words:
        by_len.setdefault(len(w), set()).add(w)

    valid = set(by_len.get(5, set()))

    # web2 has almost no inflected forms, so generate the common ones.
    for w in by_len.get(4, ()):
        if not w.endswith(("s", "x", "z", "ch", "sh")):
            valid.add(w + "s")                     # cats, cares
        if w.endswith("e"):
            valid.add(w + "d")                     # cared, hoped
            valid.add(w + "r")                     # safer, wider
    for w in by_len.get(3, ()):
        if w.endswith(("s", "x", "z")):
            valid.add(w + "es")                    # boxes, buses
        if w[-1] not in "aeiouy":
            valid.add(w + "ed")                    # aimed, asked
        if w.endswith("y") and w[1] not in "aeiou":
            valid.add(w[:2] + "ies")               # cries, spies
            valid.add(w[:2] + "ied")               # cried, spied

    extra = [w for w in read_words(ROOT / "tools" / "extra_valid.txt") if FIVE.match(w)]
    valid.update(extra)
    valid.update(answers)

    rng = random.Random(SEED)
    shuffled = answers[:]
    rng.shuffle(shuffled)

    out = ROOT / "js" / "words.js"
    out.write_text(
        "// Generated by tools/build_words.py. Do not edit by hand.\n"
        f"// {len(shuffled)} answers, {len(valid)} valid guesses.\n"
        f'export const ANSWERS = "{" ".join(shuffled)}".split(" ");\n'
        f'export const VALID = new Set("{" ".join(sorted(valid))}".split(" "));\n'
    )
    missing = [w for w in answers if w not in by_len.get(5, set())]
    print(f"answers: {len(answers)} (dupes removed: {dupes})")
    print(f"valid guesses: {len(valid)}")
    print(f"answers not in web2 (still accepted): {len(missing)}: {' '.join(missing)}")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
